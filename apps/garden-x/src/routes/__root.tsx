function RootComponent() {
  const { queryClient } = Route.useRouteContext();

  return (
    <QueryClientProvider client={queryClient}>
      <GardenProvider>
        <GardenExperience />
      </GardenProvider>
    </QueryClientProvider>
  );
}

function GardenExperience() {
  const { language, appearance } = useGarden();
  const pathname = useRouterState({ select: (state) => state.location.pathname });

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  useEffect(() => {
    const media = window.matchMedia("(prefers-color-scheme: dark)");
    const apply = () => document.documentElement.classList.toggle("dark", appearance === "dark" || (appearance === "system" && media.matches));
    apply();
    media.addEventListener("change", apply);
    return () => media.removeEventListener("change", apply);
  }, [appearance]);

  return (
    <>
      {pathname.startsWith("/shared/") ? <Outlet /> : <AppShell><Outlet /></AppShell>}
      <Toaster position="top-center" />
    </>
  );
}